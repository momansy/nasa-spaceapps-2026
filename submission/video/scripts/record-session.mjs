await wait('mg-intro', 40_000);
cast.mark('mg-intro');
await wait('mg-play', 20_000);
cast.mark('mg-play');
// Keyboard throttle controller from the canvas' aria status (in band / over / under).
await page.evaluate(() => document.querySelector('[data-testid="mg-play"] canvas')?.focus());
const t0 = Date.now();
while (Date.now() - t0 < 30_000) {
  if (await tid('mg-result').isVisible().catch(() => false)) break;
  const txt = await page.evaluate(() => document.querySelector('[data-testid="mg-play"] canvas')?.getAttribute('aria-valuetext') ?? '');
  if (/OVERLOAD/.test(txt)) await page.keyboard.press('ArrowDown');
  else if (/TOO SLOW/.test(txt)) await page.keyboard.press('ArrowUp');
  await sleep(90);
}
await wait('mg-result', 40_000);
cast.mark('mg-result');
await sleep(4500);
await tid('mg-continue').click();
await tid('console-blackout').waitFor({ timeout: 40_000 }).catch(() => {});
