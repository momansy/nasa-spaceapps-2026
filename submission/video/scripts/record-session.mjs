await tid('stage-pick').waitFor({ timeout: 15_000 });
cast.mark('pick');
await sleep(1500);
await tid('pick-fairing_small').click();
await tid('stage-result').waitFor({ timeout: 20_000 });
cast.mark('result3');
await wait('screen-poll', 40_000);
cast.mark('poll');
await tid('poll-my-call').waitFor({ timeout: 30_000 });
cast.mark('poll-my-call');
await sleep(2000);
await tid('poll-go').click();
await tid('poll-result').waitFor({ timeout: 40_000 });
cast.mark('poll-result');
await wait('console-screen', 30_000);
cast.mark('console');
await tid('console-alert').first().waitFor({ timeout: 40_000 });
