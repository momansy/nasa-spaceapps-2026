cast.mark('debrief-scroll');
for (let i = 0; i < 14; i++) { await page.mouse.wheel(0, 160); await sleep(450); }
cast.mark('debrief-facts');
const facts = page.locator('.db-facts');
if (await facts.count()) { await facts.first().scrollIntoViewIfNeeded(); }
await sleep(4000);
for (let i = 0; i < 6; i++) { await page.mouse.wheel(0, 160); await sleep(450); }
await sleep(2000);
cast.mark('codex');
await tid('open-codex').click();
await wait('codex-sheet');
await sleep(1500);
await tid('codex-item').first().click();
await sleep(3000);
await page.keyboard.press('Escape'); await page.keyboard.press('Escape');
await sleep(600);
cast.mark('settings');
await tid('open-settings').click();
await wait('settings-sheet');
await sleep(2000);
await tid('pref-highContrast').click();
await sleep(800);
const larger = tid('text-larger');
for (let i = 0; i < 8 && (await larger.isEnabled()); i++) { await larger.click(); await sleep(350); }
