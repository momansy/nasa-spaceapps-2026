// Records the scripted mock phone session (?mock=1) end to end with human pacing.
import { chromium, newPhone, startCast, sleep } from './cast.mjs';

const OUT = `${(process.env.TEMP ?? '/tmp').split(String.fromCharCode(92)).join('/')}/demo-video/rec`;
const speed = process.argv[2] ?? '1';
const browser = await chromium.launch();
const ctx = await newPhone(browser);
const page = await ctx.newPage();
page.on('pageerror', (e) => console.log('pageerror', String(e)));
const tid = (id) => page.getByTestId(id);
const wait = (id, timeout = 60_000) => tid(id).first().waitFor({ state: 'visible', timeout });
const stage = (s, timeout = 60_000) => page.locator(`[data-testid="screen-vote"][data-stage="${s}"]`).waitFor({ state: 'visible', timeout });
const goToCard = async (i) => { await page.locator('.dot').nth(i).click(); await sleep(700); };

await page.goto(`http://127.0.0.1:4173/?mock=1&speed=${speed}&room=KQXM`);
await wait('screen-join');
await sleep(500);
const cast = await startCast(page, `${OUT}/session-frames`);
cast.mark('join');
await sleep(1500);
await tid('join-nick').click();
await tid('join-nick').pressSequentially('Ada', { delay: 180 });
await sleep(600);
await tid('join-submit').click();
await wait('screen-lobby');
cast.mark('lobby');
await page.locator('.crew > li').nth(4).waitFor({ timeout: 20_000 });
await wait('screen-role', 20_000);
cast.mark('role');
await sleep(4000);
await page.mouse.wheel(0, 300); await sleep(1500);
await tid('role-ready').click();
await wait('screen-build', 20_000);
cast.mark('briefing');
await stage('REVEAL');
cast.mark('reveal');
await stage('PREDICT');
cast.mark('predict');
await sleep(1500);
await tid('predict-2').click();
await tid('predict-result').waitFor({ timeout: 30_000 });
cast.mark('predict-result');
await stage('INSPECT');
cast.mark('inspect');
await sleep(2500);
await page.locator('[data-testid="card-eng_kerolox_workhorse"] .stat__btn').nth(1).click();
cast.mark('stat-explain');
await sleep(2500);
await page.keyboard.press('Escape').catch(() => {});
await goToCard(1); cast.mark('card1'); await sleep(1800);
await goToCard(2); cast.mark('card2-warnings'); await sleep(2500);
await page.locator('[data-testid="card-eng_hydrolox_high_efficiency"] [data-testid="viewer-expand"]').click();
await wait('viewer-sheet');
cast.mark('viewer');
await sleep(3500);
await page.keyboard.press('Escape');
await stage('VOTE');
cast.mark('vote');
await goToCard(0);
await sleep(800);
await tid('cast').click();
cast.mark('cast');
await tid('stage-result').waitFor({ timeout: 40_000 });
cast.mark('result');
await wait('screen-build', 20_000);
cast.mark('build');
await tid('stage-quick').waitFor({ timeout: 30_000 });
cast.mark('quick');
await sleep(1500);
await tid('quick-TEST').click();
await stage('INSPECT');
cast.mark('inspect2');
await tid('veto-flash').waitFor({ timeout: 20_000 });
cast.mark('veto-flash');
await stage('VOTE');
cast.mark('vote2');
await goToCard(2);
await sleep(800);
await tid('open-pings').click();
await wait('ping-sheet');
cast.mark('pings');
await sleep(1500);
await tid('ping-LIKE_THIS').click();
await sleep(600);
await tid('cast').click();
cast.mark('cast2');
await tid('stage-result').waitFor({ timeout: 40_000 });
