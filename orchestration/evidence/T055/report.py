import sys, os, re, subprocess, unicodedata
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont
repo, ref, out = sys.argv[1:4]
os.chdir(repo)
ls = subprocess.check_output(["git","ls-tree","-r","--name-only",ref]).decode().splitlines()
def player_visible(f):
    if re.match(r"^data/strings/en[^/]*\.json$", f): return True
    if not f.startswith("unity/MissionForge/Assets/MissionForge/"): return False
    if "/Editor/" in f or "/Tests/" in f or "/Evidence/" in f: return False
    if "/Resources/" in f and re.search(r"/en[^/]*\.json$", f): return True
    return f.endswith((".cs", ".uxml"))
chars = {}
for f in ls:
    if not player_visible(f): continue
    t = subprocess.check_output(["git","show",f"{ref}:{f}"]).decode("utf-8","replace")
    if f.endswith(".cs"):
        # only string literals, not comments
        t = " ".join(re.findall(r'"(?:[^"\\\n]|\\.)*"', re.sub(r"//[^\n]*", "", t)))
    for ch in t:
        if ord(ch) > 127 and not unicodedata.category(ch).startswith("C"):
            chars.setdefault(ch, set()).add(f)
F = "unity/MissionForge/Assets/MissionForge/UI/Fonts/"
old_plex = TTFont("/tmp/t055-oldfonts/ibm-plex-sans-400.ttf").getBestCmap()
new_plex = TTFont(F + "ibm-plex-sans-400.ttf").getBestCmap()
oxa = TTFont(F + "oxanium-700.ttf").getBestCmap()
mono = TTFont(F + "IBMPlexMono-Regular.ttf").getBestCmap()
rows = []
for ch in sorted(chars, key=ord):
    c = ord(ch)
    rows.append((ch, c, unicodedata.name(ch, "?"), c in old_plex, c in new_plex, c in oxa, c in mono, len(chars[ch]), sorted(chars[ch])[0]))
yn = lambda b: "yes" if b else "**no**"
with open(os.path.join(out, "CHARACTERS.md"), "w") as fh:
    fh.write(f"# T055 non-ASCII characters in player-visible host text\n\nSource: `data/strings/en*.json` plus English JSON string tables under `Resources/` and string literals in runtime C# and UXML under `unity/MissionForge/Assets/MissionForge/` (Editor, Tests and Evidence folders excluded), at `{ref}` (main + T027). Generated by `report.py` with fontTools.\n\n")
    fh.write("Body text uses IBM Plex Sans, headings Oxanium, codes IBM Plex Mono. After T055, any glyph a font lacks falls back to the full IBM Plex Sans through the global fallback in `MissionForgeTextSettings.asset`.\n\n")
    fh.write("| Char | Code point | Name | Plex Sans before (subset) | Plex Sans after (full) | Oxanium (own glyph) | Plex Mono | Files | Example file |\n|---|---|---|---|---|---|---|---|---|\n")
    for ch, c, n, a, b, o, m, k, ex in rows:
        shown = {0x2009: "(thin space)", 0x202F: "(narrow nbsp)", 0x00A0: "(nbsp)"}.get(c, ch)
        fh.write(f"| {shown} | U+{c:04X} | {n.title()} | {yn(a)} | {yn(b)} | {yn(o)} | {yn(m)} | {k} | `{ex}` |\n")
    miss_before = [r for r in rows if not r[3]]
    miss_after = [r for r in rows if not r[4]]
    fh.write(f"\n**{len(rows)}** distinct characters. Missing from body font before: **{len(miss_before)}** ({' '.join(r[0] for r in miss_before)}). Missing after: **{len(miss_after)}** {(' '.join(r[0] for r in miss_after)) if miss_after else ''}.\n")
# specimen image
samples = ["10-storey building ≈ 30 m", "Fuel cells (H₂/O₂)", "Suborbital, ≥100 km apogee", "Δv 9.70 km/s · ±0.2° · 3 × 400 kg", "Descent: drogues → mains  ≤ 1.2×  −20%"]
W, H = 1800, 140 + 2 * len(samples) * 70 + 60
img = Image.new("RGB", (W, H), (12, 24, 40)); d = ImageDraw.Draw(img)
lab = ImageFont.truetype(F + "IBMPlexMono-Regular.ttf", 26)
def draw_line(y, text, font_path, cmap, fallback_cmap=None):
    f = ImageFont.truetype(font_path, 44); x = 40
    for ch in text:
        if ord(ch) in cmap or ch == " ":
            d.text((x, y), ch, font=f, fill=(235, 240, 245)); x += f.getlength(ch)
        elif fallback_cmap is not None and ord(ch) in fallback_cmap:
            ff = ImageFont.truetype(F + "ibm-plex-sans-400.ttf", 44); d.text((x, y), ch, font=ff, fill=(120, 230, 200)); x += ff.getlength(ch)
        else:
            d.rectangle([x + 4, y + 8, x + 26, y + 50], outline=(255, 90, 90), width=3); x += 32
d.text((40, 30), "BEFORE: subset IBM Plex Sans as shipped (red boxes = missing glyph, shown as �/tofu in the WebGL host)", font=lab, fill=(255, 150, 150))
y = 80
for s in samples: draw_line(y, s, "/tmp/t055-oldfonts/ibm-plex-sans-400.ttf", old_plex); y += 70
d.text((40, y + 20), "AFTER: full IBM Plex Sans (OFL); Oxanium headings fall back to it (teal = fallback glyph)", font=lab, fill=(150, 255, 200)); y += 70
for s in samples[:3]: draw_line(y, s, F + "ibm-plex-sans-400.ttf", new_plex); y += 70
for s in samples[3:]: draw_line(y, s, F + "oxanium-700.ttf", oxa, new_plex); y += 70
img.save(os.path.join(out, "glyph-specimen-before-after.png"))
print(open(os.path.join(out, "CHARACTERS.md")).read()[-600:])
