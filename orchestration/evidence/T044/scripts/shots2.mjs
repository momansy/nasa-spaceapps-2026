import { createRequire } from 'node:module';
const require = createRequire('/tmp/t044/clone2/tools/e2e/x.js');
const { chromium } = require('@playwright/test');
const out = '/Users/alainieh/Developer/Nasa/orchestration/evidence/T044/';
const b = await chromium.launch({ headless: true, args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--enable-webgl','--ignore-gpu-blocklist'] });
const hctx = await b.newContext({ viewport: { width: 1920, height: 1080 } });
const hp = await hctx.newPage();
let code = null; const frames = [];
hp.on('websocket', ws => { ws.on('framereceived', f => { const s = String(f.payload); frames.push(s.slice(0,160)); const m = s.match(/"room"\s*:\s*"([A-Z0-9]{4})"/); if (m && !code) code = m[1]; }); });
await hp.goto('http://localhost:8080/play/host/?server=ws://localhost:8787', { waitUntil: 'load' });
await hp.waitForTimeout(45000);
await hp.mouse.click(236, 912);
for (let i = 0; i < 30 && !code; i++) await hp.waitForTimeout(1000);
console.log('room code', code); console.log(frames.slice(0,6).join('\n'));
await hp.waitForTimeout(8000);
await hp.screenshot({ path: out+'05a-host-lobby-empty.png' });
if (code) {
  const pctx = await b.newContext({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
  const pp = await pctx.newPage();
  const errs = []; pp.on('pageerror', e => errs.push(e.message)); pp.on('console', m => { if (m.type()==='error') errs.push(m.text()); });
  await pp.goto('http://localhost:8080/play/client/', { waitUntil: 'networkidle' });
  await pp.waitForTimeout(1500);
  await pp.screenshot({ path: out+'06a-phone-join-screen.png' });
  const inputs = await pp.$$eval('input', is => is.map(i => ({ n: i.name, p: i.placeholder, t: i.type, a: i.getAttribute('aria-label') })));
  console.log('inputs', JSON.stringify(inputs));
  const ins = await pp.$$('input');
  await ins[0].fill(code);
  if (ins[1]) await ins[1].fill('JudgeTest');
  await pp.screenshot({ path: out+'06b-phone-filled.png' });
  const btns = await pp.$$eval('button', bs => bs.map(x => x.innerText));
  console.log('buttons', JSON.stringify(btns));
  await pp.keyboard.press('Enter');
  await pp.waitForTimeout(4000);
  await pp.screenshot({ path: out+'06c-phone-after-join.png' });
  console.log('errs', errs.join(' | '));
  await hp.waitForTimeout(6000);
  await hp.screenshot({ path: out+'05b-host-lobby-with-phone.png' });
}
await b.close();
