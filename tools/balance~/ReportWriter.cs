using System.Diagnostics;
using System.Globalization;
using System.Text;
using System.Text.Json;
using MissionForge.Core.Data;

namespace MissionForge.Balance;

internal static class ReportWriter
{
    public static string Commit()
    {
        try
        {
            using var process = Process.Start(new ProcessStartInfo
            {
                FileName = "git",
                Arguments = "rev-parse --short HEAD",
                RedirectStandardOutput = true,
                RedirectStandardError = true,
                UseShellExecute = false,
                CreateNoWindow = true,
            });
            if (process == null) return "unavailable";
            var value = process.StandardOutput.ReadToEnd().Trim();
            process.WaitForExit();
            return process.ExitCode == 0 && value.Length > 0 ? value : "unavailable";
        }
        catch (Exception)
        {
            return "unavailable";
        }
    }

    public static void Write(BalanceReport report, string outputPath)
    {
        Directory.CreateDirectory(outputPath);
        var markdown = Markdown(report);
        var json = Json(report);
        File.WriteAllText(Path.Combine(outputPath, "balance-report.md"), markdown, new UTF8Encoding(false));
        File.WriteAllText(Path.Combine(outputPath, "balance-report.json"), json, new UTF8Encoding(false));
    }

    private static string Markdown(BalanceReport report)
    {
        var text = new StringBuilder();
        text.AppendLine("# MissionForge balance report");
        text.AppendLine();
        text.AppendLine("Generated by `tools/balance~` (task T012). The tool only reports: it changes no data, Core code or Core solution.");
        text.AppendLine();
        text.AppendLine($"Commit: `{report.Commit}`  ");
        text.AppendLine($"Seed: `{report.Seed}`  ");
        text.AppendLine($"Maximum complete builds evaluated per contract (`--max-evals`): `{report.MaxEvalsPerContract}`");
        text.AppendLine();
        text.AppendLine("## Contract summary");
        text.AppendLine();
        text.AppendLine("| Contract | Valid / evaluated | Capped | Architectures | ≥ 3 architectures | Dominant | Near-dominant | Overall |");
        text.AppendLine("|---|---:|:---:|---:|:---:|:---:|---:|:---:|");
        foreach (var contract in report.Contracts)
            text.AppendLine($"| {contract.ContractId} {Escape(contract.ContractName)} | {contract.Valid} / {contract.Evaluated} | {YesNo(contract.Capped)} | {contract.ArchitectureCount} | {PassFail(contract.ArchitecturePass)} | {DominantCell(contract)} | {contract.NearDominant.Count} | {PassFail(contract.Pass)} |");
        text.AppendLine();
        text.AppendLine("A contract passes when at least 3 architectures have a valid build within budget and schedule and no single architecture is alone on the Pareto front.");
        text.AppendLine();

        text.AppendLine("## Rules used");
        text.AppendLine();
        text.AppendLine("- **Valid build.** Every vote of Core `VoteOptions.VotesFor(contract)` is filled with an option from `VoteOptions.Offered`; Core `Validator.Validate(build, catalog, ValidationMode.Complete)` reports no Blocker; `Dashboard.Compute(...).Budget.RemainingM ≥ 0 $M`; and `Budget.TotalDays ≤ Budget.DeadlineDays`. Majors are allowed and counted. Success is always the displayed estimate `DashboardMetrics.Success`, never the hidden truth. No tests, reviews or Emergency Funding are applied (a fresh build).");
        text.AppendLine("- **Search.** The propulsion-coupled votes (launch site, both engines, both counts, both tanks, material, strap-on, separation, fairing, booster recovery, heat shield, escape system, capsule and lander, where the contract votes them) are enumerated depth-first with `BuildState.WithChoice`. The architecture votes (first-stage engine, upper-stage engine, strap-on, booster recovery) are decided first; each surviving combination is a *stratum*. The remaining coupled votes follow, with both tanks last. `FixSearch` is not used.");
        text.AppendLine("- **Pruning (sound).** A branch is cut on a `ValidationMode.Partial` Blocker. Core judges lift-off TWR and Δv as soon as the engines and tanks are decided, so the tanks are decided last: every other coupled mass, thrust and Δv input is then final, and the votes filled later can only add mass. A branch is also cut when the cost lower bound (`decided parts cost × (1 + largest assurance discount)`) exceeds the budget, or the schedule lower bound (`(longest lead + decided integration days + most negative integration still possible) × (1 + largest assurance schedule discount)`) exceeds the deadline. Part costs are never negative and engine counts are at least 1, so both bounds only grow as votes are decided.");
        text.AppendLine("- **Other votes.** Each coupled combination is completed twice, greedily in vote order: the option with the lowest displayed total cost (*cheapest*) and the option with the highest displayed success (*most reliable*). When both give the same build it is evaluated once. The greedy choice is memoized on the offered option sets; this is exact in Core because non-propulsion part costs are additive and context free and displayed success is a product of per-part factors.");
        text.AppendLine("- **Cap and sampling.** The evaluation budget is shared equally among the strata still to search (unused budget moves to later strata). A stratum whose subtree fits half its share is enumerated exhaustively; a larger one is sampled with seeded random descents (SplitMix64 from `--seed`, the contract and the stratum) until its share is spent. A contract with any sampled stratum is reported as capped; its counts are for the builds evaluated, not the whole space.");
        text.AppendLine("- **Meaningfully different (Decision).** Builds are grouped by architecture `(first-stage engine, upper-stage engine, booster-recovery family, strap-on)`. The recovery families are expendable, parachute and propulsive (return to launch site and drone ship are one family). A contract needs at least 3 architectures with a valid build.");
        text.AppendLine("- **Representative per architecture (Decision).** The valid build with the lowest balanced regret `cost / budget + days / deadline + (1 − displayed success)`; ties go to higher success, lower cost, fewer days, then part IDs.");
        text.AppendLine("- **Dominance.** The Pareto front of the representatives on cost ↓, schedule days ↓ and displayed success ↑. *Dominant*: one architecture alone on the front. *Near-dominant*: a representative within 2% of the best representative on every axis (`cost ≤ 1.02 × min`, `days ≤ 1.02 × min`, `success ≥ 0.98 × max`). As a diagnostic the report also counts the architectures with any build on the Pareto front of **all** valid builds.");
        text.AppendLine("- **Archetypes (design 18.1).** Cheapest valid build (cheap and risky), highest displayed success (expensive and safe), and the highest-success build with parachute or propulsive booster recovery (best reusable).");
        text.AppendLine("- **Unused parts (design 18.1, Decision).** Parts that appear in no build on the Pareto front of *all* valid builds of any evaluated contract. The all-build front is used rather than the representatives' front because the representative rule favours cheap builds and would list every premium part. Parts of the non-coupled (fill) votes are only tried as the cheapest or most reliable option, so a middle option there is unused by construction; it is labelled as such.");
        text.AppendLine("- **Model boundaries.** Δv, TWR, mass, entry, power and data come from Core's physical or simplified-physical models. Cost (`$M`), schedule (`days`), reliability, the success estimate, and every threshold of this report (3 architectures, 2%, the regret weights) are game values.");
        text.AppendLine();

        foreach (var contract in report.Contracts)
        {
            text.AppendLine($"## {contract.ContractId} — {Escape(contract.ContractName)}");
            text.AppendLine();
            text.AppendLine($"Budget `{Num(contract.BudgetM)} $M`, deadline `{Num(contract.DeadlineDays)} days`.");
            text.AppendLine();
            text.AppendLine($"- **Valid / evaluated:** `{contract.Valid}` / `{contract.Evaluated}` complete builds from `{contract.LeavesVisited}` coupled combinations. Capped: **{YesNo(contract.Capped)}** (`{contract.Strata}` strata: `{contract.ExhaustiveStrata}` exhaustive, `{contract.SampledStrata}` sampled).");
            text.AppendLine($"- **Architectures with a valid build:** `{contract.ArchitectureCount}`: **{PassFail(contract.ArchitecturePass)}** against ≥ 3.");
            text.AppendLine($"- **Dominance:** {DominanceText(contract)} Near-dominant: {(contract.NearDominant.Count == 0 ? "none" : string.Join("; ", contract.NearDominant.Select(a => $"`{a}`")))}.");
            text.AppendLine($"- **All-build Pareto front (diagnostic):** `{contract.AllBuildFrontSize}` builds from `{contract.AllBuildFrontArchitectures.Count}` architectures.");
            text.AppendLine($"- **Pruned branches:** {Counts(contract.PruneReasons)}.");
            text.AppendLine($"- **Invalid evaluated builds:** {Counts(contract.InvalidReasons)}.");
            text.AppendLine($"- **Overall:** **{PassFail(contract.Pass)}**.");
            text.AppendLine();
            text.AppendLine("### Archetypes");
            text.AppendLine();
            AppendBuild(text, "Cheapest valid (cheap and risky)", contract.Cheapest);
            AppendBuild(text, "Highest displayed success (expensive and safe)", contract.HighestSuccess);
            AppendBuild(text, "Best reusable", contract.BestReusable);
            text.AppendLine("### Pareto front of architecture representatives");
            text.AppendLine();
            if (contract.ParetoFront.Count == 0)
            {
                text.AppendLine("None.");
                text.AppendLine();
            }
            else
            {
                text.AppendLine("| Architecture | Cost ($M) | Schedule (days) | Displayed success | Majors |");
                text.AppendLine("|---|---:|---:|---:|---:|");
                foreach (var build in contract.ParetoFront)
                    text.AppendLine($"| `{build.Architecture}` | {Num(build.CostM)} | {Num(build.ScheduleDays)} | {Pct(build.SuccessEstimate)} | {build.MajorCount} |");
                text.AppendLine();
            }
        }

        text.AppendLine("## Unused parts");
        text.AppendLine();
        text.AppendLine("Parts appearing in no build on the all-build Pareto front of any evaluated contract.");
        text.AppendLine();
        if (report.UnusedParts.Count == 0) text.AppendLine("None.");
        else
        {
            text.AppendLine("| Category | Part | Why |");
            text.AppendLine("|---|---|---|");
            foreach (var part in report.UnusedParts) text.AppendLine($"| {part.Category} | `{part.Id}` | {part.Reason} |");
        }
        text.AppendLine();
        text.AppendLine("## Recommended data changes");
        text.AppendLine();
        text.AppendLine("Recommendations only: no data file was changed. Each is a playtest starting point derived from this run; tune values tagged `game_value`, not physical ones.");
        text.AppendLine();
        text.AppendLine("| # | File | ID | Field | Current | Proposed | Reason |");
        text.AppendLine("|---:|---|---|---|---:|---:|---|");
        var n = 0;
        foreach (var recommendation in report.Recommendations)
            text.AppendLine($"| {++n} | `{recommendation.File}` | `{recommendation.Id}` | `{recommendation.Field}` | {Escape(recommendation.CurrentValue)} | {Escape(recommendation.ProposedValue)} | {Escape(recommendation.Reason)} |");
        if (report.Recommendations.Count == 0) text.AppendLine("| — | — | — | — | — | — | No changes recommended from this run. |");
        return text.ToString().Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    private static string DominantCell(ContractResult contract) =>
        contract.ArchitectureCount == 0 ? "n/a" : contract.Dominant ? "**yes**" : "no";

    private static string DominanceText(ContractResult contract) =>
        contract.ArchitectureCount == 0 ? "not applicable (no valid build)."
        : contract.Dominant ? $"**DOMINANT**: `{contract.ParetoFront[0].Architecture}` is alone on the front."
        : $"not dominant: `{contract.ParetoFront.Count}` architectures on the front.";

    private static string Counts(SortedDictionary<string, int> counts) =>
        counts.Count == 0 ? "none" : string.Join(", ", counts.Select(kv => $"`{kv.Key}` {kv.Value}"));

    private static string Num(double value) => value.ToString("0.###", CultureInfo.InvariantCulture);
    private static string Pct(double value) => (value * 100).ToString("0.##", CultureInfo.InvariantCulture) + "%";

    private static string Json(BalanceReport report)
    {
        var document = new
        {
            schema_version = 1,
            commit = report.Commit,
            seed = report.Seed,
            max_evals_per_contract = report.MaxEvalsPerContract,
            rules = new
            {
                required_architectures = 3,
                dominant_front_size = 1,
                near_dominant_tolerance_fraction = 0.02,
                success_source = "DashboardMetrics.Success (displayed estimate)",
            },
            contracts = report.Contracts.Select(contract => new
            {
                id = contract.ContractId,
                name = contract.ContractName,
                evaluated = contract.Evaluated,
                valid = contract.Valid,
                capped = contract.Capped,
                budget_M = contract.BudgetM,
                deadline_days = contract.DeadlineDays,
                coupled_combinations = contract.LeavesVisited,
                strata = contract.Strata,
                exhaustive_strata = contract.ExhaustiveStrata,
                sampled_strata = contract.SampledStrata,
                partial_blocker_prunes = contract.PartialBlockerPrunes,
                cost_lower_bound_prunes = contract.CostLowerBoundPrunes,
                schedule_lower_bound_prunes = contract.ScheduleLowerBoundPrunes,
                prune_reasons = contract.PruneReasons,
                invalid_reasons = contract.InvalidReasons,
                architectures = contract.ArchitectureCount,
                architecture_pass = contract.ArchitecturePass,
                dominant = contract.Dominant,
                dominance_pass = contract.DominancePass,
                near_dominant = contract.NearDominant.Select(ArchitectureJson),
                pass = contract.Pass,
                archetypes = new
                {
                    cheapest = BuildJson(contract.Cheapest),
                    highest_success = BuildJson(contract.HighestSuccess),
                    best_reusable = BuildJson(contract.BestReusable),
                },
                pareto_front = contract.ParetoFront.Select(BuildJson),
                all_build_front_size = contract.AllBuildFrontSize,
                all_build_front_architectures = contract.AllBuildFrontArchitectures.Select(ArchitectureJson),
            }),
            unused_parts = report.UnusedParts.Select(part => new { id = part.Id, category = part.Category, reason = part.Reason }),
            recommended_data_changes = report.Recommendations.Select(item => new
            {
                file = item.File,
                id = item.Id,
                field = item.Field,
                current = item.CurrentValue,
                proposed = item.ProposedValue,
                reason = item.Reason,
            }),
        };
        return JsonSerializer.Serialize(document, new JsonSerializerOptions { WriteIndented = true }) + "\n";
    }

    private static object? BuildJson(BuildResult? build) => build == null ? null : new
    {
        architecture = ArchitectureJson(build.Architecture),
        cost_M = Round(build.CostM),
        schedule_days = Round(build.ScheduleDays),
        displayed_success = Round(build.SuccessEstimate),
        majors = build.MajorCount,
        variant = build.Variant,
        parts = build.Choices.Select(choice => new { slot = choice.Slot, id = choice.PartId }),
    };

    private static object ArchitectureJson(Architecture architecture) => new
    {
        first_stage_engine = architecture.FirstStageEngine,
        upper_stage_engine = architecture.UpperStageEngine,
        recovery_family = architecture.RecoveryFamily,
        strap_on = architecture.StrapOn,
    };

    private static void AppendBuild(StringBuilder text, string label, BuildResult? build)
    {
        text.AppendLine($"#### {label}");
        text.AppendLine();
        if (build == null)
        {
            text.AppendLine("None found.");
            text.AppendLine();
            return;
        }
        text.AppendLine($"Architecture: `{build.Architecture}`  ");
        text.AppendLine($"Metrics: `{Num(build.CostM)} $M`; `{Num(build.ScheduleDays)} days`; `{Pct(build.SuccessEstimate)}` displayed success; `{build.MajorCount}` Majors; fill variant `{build.Variant}`.  ");
        text.AppendLine("Parts: " + string.Join(", ", build.Choices.Select(choice => $"`{choice.Slot}={choice.PartId}`")));
        text.AppendLine();
    }

    private static double Round(double value) => Math.Round(value, 9, MidpointRounding.AwayFromZero);
    private static string YesNo(bool value) => value ? "yes" : "no";
    private static string PassFail(bool value) => value ? "PASS" : "FAIL";
    private static string Escape(string value) => value.Replace("|", "\\|", StringComparison.Ordinal);
}
