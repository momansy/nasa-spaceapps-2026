export function buildCredits() {
  const body = [aiDisclosure(), factsSection(), licencesSection(), disclaimers(), teamSection()].join('\n');
  const html = page({
    title: 'Credits',
    lede: 'AI-assistance disclosure, data sources, third-party licences and disclaimers. <a href="#team">Team</a> &middot; <a href="#ai">AI</a> &middot; <a href="#facts">Facts</a> &middot; <a href="#licences">Licences</a>',
    body,
  });
  writeFileSync(join(REPO, 'docs', 'play', 'credits.html'), html);
  console.log(`docs/play/credits.html written (${(html.length / 1024).toFixed(0)} kB)`);

  const judgesPath = join(REPO, 'JUDGES.md');
  if (existsSync(judgesPath)) {
    const md = readFileSync(judgesPath, 'utf8');
    const rendered = markdownToHtml(md);
    const t = /<!-- title: (.*?) -->/.exec(rendered);
    const jhtml = page({
      title: 'For judges',
      lede: 'The same text as <code>JUDGES.md</code> in the repository.',
      body: rendered.replace(/<!-- title: .*? -->\n?/, ''),
    });
    writeFileSync(join(REPO, 'docs', 'play', 'judges.html'), jhtml);
    console.log(`docs/play/judges.html written from JUDGES.md${t ? ` ("${t[1]}")` : ''}`);
  } else {
    console.warn('JUDGES.md not found: docs/play/judges.html not written');
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  try {
    buildCredits();
  } catch (e) {
    console.error(String(e.stack || e));
    process.exit(1);
  }
}
