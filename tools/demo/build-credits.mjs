/** The markdown tables of a repository file, rendered. Bare <url> links become anchors. */
function mdTableFrom(...path) {
  const rows = read(...path)
    .split(/\r?\n/)
    .filter((l) => l.startsWith('|'));
  return markdownToHtml(rows.join('\n').replace(/<(https?:\/\/[^>\s]+)>/g, '[$1]($1)'));
}

